// Helpers
export function getUserById(id: string): BUser | undefined {
  return MOCK_USERS.find(u => u.id === id)
}

export function getDeptById(deptId: string) {
  const { BCL_DEPARTMENTS } = require("./constants")
  return BCL_DEPARTMENTS.find((d: any) => d.id === deptId)
}

export function getTasksForUser(tasks: BTask[], userId: string): BTask[] {
  return tasks.filter(t => t.createdByUserId === userId || t.assignedToUserId === userId)
}

export function getOverdueTasks(tasks: BTask[], today = TODAY): BTask[] {
  return tasks.filter(t => t.dueDate < today && t.status !== "done" && t.status !== "cancelled")
}

export function calcCompletionRate(tasks: BTask[]): number {
  if (tasks.length === 0) return 0
  return Math.round((tasks.filter(t => t.status === "done").length / tasks.length) * 100)
}
